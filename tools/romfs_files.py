#!/usr/bin/env python3
"""Writes runtime/game_addresses/romfs_files.h: a sorted table of 64-bit hashes, one per RomFS file of every supported
game version, from extracted reference copies of the game files. Only the hashes ship (no file names, no game data).

Each hash is FNV-1a 64 over the file's path relative to romfs ("region_common/event/x.bfevfl", '/' separators), a 0
byte, then its size in decimal ("2712"). The mask says which versions have that exact file: bit 0 = 1.0.0, bit 1 =
1.0.1 / 1.1.0 (the same RomFS). The runtime and the start screen hash every file of a copy the same way
(game_romfs_check_file in runtime/game_addresses.c) and log the ones that aren't the game's.

  python3 tools/romfs_files.py [--dir ~/Developer/LAS-versions]   (folders 1.0.0, 1.0.1 and 1.1.0, each with romfs/)
"""
import argparse
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT/'runtime/game_addresses/romfs_files.h'
VERSIONS = (('1.0.0', 1), ('1.0.1', 2), ('1.1.0', 2))  # (release folder, mask bit)


def fnv1a64(data: bytes) -> int:
    h = 0xcbf29ce484222325
    for b in data:
        h = ((h ^ b) * 0x100000001b3) & 0xffffffffffffffff
    return h


def entry_hash(rel: str, size: int) -> int:
    return fnv1a64(rel.encode() + b'\0' + str(size).encode())


def romfs_files(romfs: Path) -> dict:
    """{relative path: size} of every regular file (hidden names skipped, as the runtime's walk does)."""
    files = {}
    for dirpath, dirnames, filenames in os.walk(romfs):
        dirnames[:] = [d for d in dirnames if not d.startswith('.')]
        for name in filenames:
            if name.startswith('.'):
                continue
            p = Path(dirpath, name)
            if p.is_file():
                files[p.relative_to(romfs).as_posix()] = p.stat().st_size
    return files


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--dir', default=os.path.expanduser('~/Developer/LAS-versions'))
    args = ap.parse_args()
    masks, seen = {}, {}
    for release, bit in VERSIONS:
        files = romfs_files(Path(args.dir, release, 'romfs'))
        assert files, f'no RomFS files in {args.dir}/{release}/romfs'
        if bit in seen:  # (releases sharing a bit must have the same files)
            assert files == seen[bit], f'{release}: not the same RomFS as the other release of its version'
        seen[bit] = files
        for rel, size in files.items():
            h = entry_hash(rel, size)
            masks[h] = masks.get(h, 0) | bit
    assert len(masks) == len({e for f in seen.values() for e in f.items()}), 'hash collision'
    lines = ['// Generated by tools/romfs_files.py: every game version\'s RomFS files as FNV-1a 64 hashes of '
             '"<path>\\0<size>",',
             '// sorted, with the versions that have them (bit 0: 1.0.0, bit 1: 1.0.1 / 1.1.0). Do not edit.',
             f'// {len(masks)} entries; 1.0.0: {sum(1 for m in masks.values() if m & 1)} files, '
             f'1.0.1 / 1.1.0: {sum(1 for m in masks.values() if m & 2)} files.']
    lines += [f'{{0x{h:016x}ull, {m}}},' for h, m in sorted(masks.items())]
    OUT.write_text('\n'.join(lines) + '\n')
    print(f'{OUT.relative_to(ROOT)}: {len(masks)} entries')


if __name__ == '__main__':
    main()
