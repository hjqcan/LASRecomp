#include "research.h"
#include <string.h>

// First four instructions, identical in the two recognized LAS executables.
// These guards supplement executable identity checks; no guest instructions are rewritten.
static const unsigned char signatures[RESEARCH_PHASE_COUNT][16]={
    {0xf3,0x0f,0x1e,0xf8,0xfd,0x7b,0x01,0xa9,0xfd,0x43,0x00,0x91,0x13,0x04,0x40,0xf9},
    {0xff,0x43,0x01,0xd1,0xf8,0x5f,0x01,0xa9,0xf6,0x57,0x02,0xa9,0xf4,0x4f,0x03,0xa9},
    {0xe8,0x0f,0x1c,0xfc,0xf6,0x57,0x01,0xa9,0xf4,0x4f,0x02,0xa9,0xfd,0x7b,0x03,0xa9},
    {0xff,0xc3,0x01,0xd1,0xe8,0x0b,0x00,0xfd,0xfb,0x0f,0x00,0xf9,0xfa,0x67,0x02,0xa9}
};
bool research_site_matches(int phase,const void *bytes,size_t size) {
    return phase>=0&&phase<RESEARCH_PHASE_COUNT&&bytes&&size>=16&&!memcmp(bytes,signatures[phase],16);
}
