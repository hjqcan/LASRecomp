bool research_seed_initializer_matches(const void *bytes,size_t size) {
    if(!bytes||size<168)return false;
    const unsigned char *p=(const unsigned char *)bytes;uint64_t hash=UINT64_C(14695981039346656037);
    for(size_t i=0;i<168;++i)hash=(hash^p[i])*UINT64_C(1099511628211);
    // Exact full initializer, identical in both recognized executables; supplements Build-ID checks.
    return hash==UINT64_C(0x856cce21632be1cf);
}
