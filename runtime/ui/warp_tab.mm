static const char *current_level(void) {
    uint64_t ps = *(uint64_t *)(uintptr_t)GA(PLAYER_STATUS_PTR);
    if (ps < GUEST_LO || ps >= GUEST_HI) return "";
    const char *s = (const char *)(uintptr_t)ps;
    for (int i = 0; i < 0x40; i++) {
        if (!s[i]) return s;
        if (!isprint((unsigned char)s[i])) return "";
    }
    return "";
}

// ---------- places ----------
// A place in the list: a spot of warp_data.h, or a dungeon room (a unit of warp_rooms.h)
struct Entry {
    int spot = -1;          // kWarpSpots index (-1: a room)
    const char *level = "";
    int room = -1;          // dungeon: the room (its unit's first cell) in warp_level(level).rooms
    std::string name, sub;  // English (shown through L_line / L)
    std::string desc;       // the description under the map
    std::string id;         // "S/<level>/<locator>" or "R/<level>/<room key>" (the rows' and the map's key)
    int icon = WI_PIN;
    int sq_r = -1, sq_c = -1;  // the island square (overworld spots, and houses / caves by their door)
};
struct Area {
    int sec;              // 0 Overworld, 1 Houses & caves, 2 Dungeons
    std::string name;     // English
    std::vector<Entry> entries;
    std::vector<int> spots;  // (its spots in warp_data.h)
    const char *level = nullptr;  // dungeon: its level (rooms built on first use)
    bool built = false;
    int region = -1;      // overworld: the island region
};
enum { SEC_OW, SEC_IN, SEC_DG };
static const char *const kSecName[] = {"Overworld", "Houses & caves", "Dungeons"};

static std::vector<Area> g_areas;
static WarpIsland g_island;
static std::vector<int> g_spot_r, g_spot_c, g_spot_icon;  // per spot: its square on the island (-1), its icon

// "Outside Mt. Tamaranch cave (east) (02P) #2" -> "Mt. Tamaranch cave (east)" (the code and the count dropped)
static std::string clean_label(const char *l) {
    std::string s = l;
    size_t h = s.rfind(" #");
    if (h != std::string::npos && h + 3 == s.size() && isdigit((unsigned char)s[h + 2])) s.erase(h);
    for (size_t p; (p = s.find(" (")) != std::string::npos;) {  // codes: "(02P)", "(08D_b)", "(Lv07_06B_from_02B_02F)"
        size_t e = s.find(')', p);
        if (e == std::string::npos) break;
        std::string in = s.substr(p + 2, e - p - 2);
        bool code = (in.size() >= 3 && isdigit((unsigned char)in[0]) && isdigit((unsigned char)in[1]) && isupper((unsigned char)in[2])) ||
                    !in.compare(0, 2, "Lv");
        if (!code) { size_t nx = s.find(" (", e); if (nx == std::string::npos) break; std::string head = s.substr(0, e + 1);
            std::string rest = clean_label(s.substr(e + 1).c_str()); return head + rest; }
        s.erase(p, e - p + 1);
    }
    size_t sl = s.find(" / ");  // ("Color Dungeon / PanelLv10ClothesDungeon")
    if (sl != std::string::npos) s.erase(sl);
    return s;
}
static bool code_of(const char *label, int *r, int *c) {  // "(02P)" -> row 1, column 15
    for (const char *p = strchr(label, '('); p; p = strchr(p + 1, '('))
        if (isdigit((unsigned char)p[1]) && isdigit((unsigned char)p[2]) && p[3] >= 'A' && p[3] <= 'P') {
            *r = (p[1] - '0') * 10 + (p[2] - '0') - 1, *c = p[3] - 'A';
            return *r >= 0 && *r < 16;
        }
    return false;
}
static const char *compass(float fy, float fx) {  // (0-1 across the area)
    static const char *const k[3][3] = {{"north-west", "north", "north-east"}, {"west", "middle", "east"}, {"south-west", "south", "south-east"}};
    int v = fy < 1 / 3.0f ? 0 : fy > 2 / 3.0f ? 2 : 1, h = fx < 1 / 3.0f ? 0 : fx > 2 / 3.0f ? 2 : 1;
    return k[v][h];
}
static int icon_of(const WarpSpot &w) {
    const char *l = w.label;
    if (strstr(l, "Manbo")) return WI_NOTE;
    if (strstr(l, "Warp hole")) return WI_WARP;
    if (w.group != 0) return strstr(l, "Entrance") ? WI_ENTRANCE : strstr(l, "stairs") ? WI_STAIRS : strstr(l, "ladder") ? WI_LADDER : WI_ROOM;
    if (strstr(l, "Phone booth")) return WI_PHONE;
    if (strstr(l, "Great Fairy")) return WI_FAIRY;
    if (strstr(l, "Level ") || strstr(l, "Color Dungeon") || strstr(l, "Wind Fish's Egg")) return WI_DUNGEON;
    if (strstr(l, "boat")) return WI_BOAT;
    for (const char *k : {"cave", "passage", "Tunnel", "hideout", "hollow", "well", "exit", "Maw entrance"})
        if (strstr(l, k)) return WI_CAVE;
    return !strncmp(l, "Outside ", 8) ? WI_DOOR : WI_PIN;
}

static void build_places(void) {
    g_spot_r.assign(kNumSpots, -1), g_spot_c.assign(kNumSpots, -1), g_spot_icon.assign(kNumSpots, WI_PIN);
    std::map<std::string, int> area_of;  // "<sec>|<name>" -> g_areas index
    for (int i = 0; i < kNumSpots; i++) {
        const WarpSpot &w = kWarpSpots[i];
        std::string k = std::to_string(w.group) + "|" + w.area;
        if (!area_of.count(k)) {
            area_of[k] = (int)g_areas.size();
            Area a;
            a.sec = w.group, a.name = w.area;
            if (w.group == SEC_DG) a.level = w.level;
            g_areas.push_back(a);
        }
        g_areas[area_of[k]].spots.push_back(i);
        g_spot_icon[i] = icon_of(w);
        int r, c;
        if (w.group == 0 && code_of(w.label, &r, &c)) g_spot_r[i] = r, g_spot_c[i] = c;
    }
    // the island: each square goes to the region of the nearest overworld spot
    std::map<std::string, int> region;
    for (auto &a : g_areas)
        if (a.sec == SEC_OW && g_island.nregions < 32) a.region = region[a.name] = g_island.nregions, g_island.regions[g_island.nregions++] = a.name.c_str();
    for (int r = 0; r < 16; r++)
        for (int c = 0; c < 16; c++) {
            float best = 1e9f;
            for (int i = 0; i < kNumSpots; i++) {
                if (g_spot_r[i] < 0) continue;
                float d = (float)((g_spot_r[i] - r) * (g_spot_r[i] - r)) + 1.1f * (float)((g_spot_c[i] - c) * (g_spot_c[i] - c));
                if (d < best) best = d, g_island.sq[r][c].region = region[kWarpSpots[i].area];
            }
        }
    static const int pri[] = {WI_DUNGEON, WI_WARP, WI_FAIRY, WI_PHONE, WI_BOAT, WI_DOOR, WI_CAVE, WI_NOTE, WI_PIN};
    for (int p : pri)
        for (int i = 0; i < kNumSpots; i++)
            if (g_spot_r[i] >= 0 && g_spot_icon[i] == p) {
                WarpIslandSquare &q = g_island.sq[g_spot_r[i]][g_spot_c[i]];
                bool have = false;
                for (int k = 0; k < q.n; k++) have |= q.icons[k] == p;
                if (!have && q.n < 4) q.icons[q.n++] = p;
            }
    // overworld and houses / caves: their entries now (dungeons: on first use, from the level files)
    std::map<std::string, int> door_of;  // "Mt. Tamaranch cave (east)" -> its first outside spot
    for (int i = 0; i < kNumSpots; i++)
        if (kWarpSpots[i].group == 0 && !strncmp(kWarpSpots[i].label, "Outside ", 8)) {
            std::string b = clean_label(kWarpSpots[i].label).substr(8);
            if (!door_of.count(b)) door_of[b] = i;
        }
    for (auto &a : g_areas) {
        if (a.sec == SEC_DG) continue;
        int n_ent = 0, k_ent = 0;
        for (int i : a.spots) n_ent += !!strstr(kWarpSpots[i].label, "Entrance");
        for (int i : a.spots) {
            const WarpSpot &w = kWarpSpots[i];
            Entry e;
            e.spot = i, e.level = w.level, e.icon = g_spot_icon[i], e.id = std::string("S/") + w.level + "/" + w.locator;
            std::string n = clean_label(w.label);
            if (a.sec == SEC_OW) {
                e.sq_r = g_spot_r[i], e.sq_c = g_spot_c[i];
                if (!n.compare(0, 15, "Manbo's Mambo: ")) e.name = n.substr(15), e.sub = "Manbo's Mambo drop point";
                else if (!n.compare(0, 11, "Warp hole: ")) e.name = "Warp hole", e.sub = n.substr(11);
                else if (!n.compare(0, 8, "Outside ")) e.name = n.substr(8), e.sub = "Outside the door";
                else e.name = n, e.sub = "Out in the open";
            } else {
                auto d = door_of.find(a.name);
                if (d != door_of.end()) e.sq_r = g_spot_r[d->second], e.sq_c = g_spot_c[d->second];
                int r, c;
                bool code = sscanf(w.label, "Room %2d%c", &r, (char *)&c) == 2 || code_of(w.label, &r, &c);
                (void)code;
                if (strstr(w.label, "Entrance")) k_ent++, e.name = n_ent > 1 ? "Door " + std::to_string(k_ent) : "Just inside", e.sub = "Inside";
                else e.name = strstr(w.label, "stairs") ? "Stairs" : "Room", e.sub = "Inside";
            }
            a.entries.push_back(e);
        }
        // the same name twice in an area: which side of the others it is on, or a number
        for (size_t i = 0; i < a.entries.size(); i++) {
            std::vector<size_t> same;
            for (size_t j = 0; j < a.entries.size(); j++)
                if (a.entries[j].name == a.entries[i].name) same.push_back(j);
            if (same.size() < 2 || same[0] != i) continue;
            float mr = 0, mc = 0;
            for (size_t j : same) mr += a.entries[j].sq_r, mc += a.entries[j].sq_c;
            mr /= same.size(), mc /= same.size();
            std::map<std::string, int> seen;
            for (size_t j : same) {
                Entry &e = a.entries[j];
                float dr = e.sq_r - mr, dc = e.sq_c - mc;
                std::string q = a.sec != SEC_OW || (fabsf(dr) < 0.3f && fabsf(dc) < 0.3f) ? "door"
                              : fabsf(dc) >= fabsf(dr) ? (dc < 0 ? "west side" : "east side") : (dr < 0 ? "north side" : "south side");
                int k = ++seen[q];
                e.name += " (" + (q == "door" ? "door " + std::to_string(k) : k > 1 ? q + " " + std::to_string(k) : q) + ")";
            }
        }
        for (auto &e : a.entries)
            e.desc = std::string(L_line(a.name)) + ". " + L_line(e.sub) + ".";
        std::sort(a.entries.begin(), a.entries.end(), [](const Entry &x, const Entry &y) { return x.name < y.name; });
        a.built = true;
    }
    std::sort(g_areas.begin(), g_areas.end(), [](const Area &x, const Area &y) { return x.sec != y.sec ? x.sec < y.sec : x.name < y.name; });
}

// A dungeon's rooms as places: one per room (its joined cells together), named by what is in it and where it lies
static void build_dungeon(Area &a) {
    a.built = true;
    const WarpLevel &LV = warp_level(a.level);
    if (!LV.ok) {  // (the level files aren't there: its arrival points as listed)
        for (int i : a.spots) {
            Entry e;
            e.spot = i, e.level = a.level, e.name = kWarpSpots[i].label, e.icon = g_spot_icon[i];
            e.id = std::string("S/") + a.level + "/" + kWarpSpots[i].locator;
            a.entries.push_back(e);
        }
        return;
    }
    std::map<std::string, int> known;  // the level's arrival points the warp list has (their spot)
    for (int i : a.spots) known[kWarpSpots[i].locator] = i;
    std::map<std::string, int> names;
    int nside = 0;
    for (int ri = 0; ri < (int)LV.rooms.size(); ri++) {
        const WarpRoom &r = LV.rooms[ri];
        Entry e;
        e.level = a.level, e.room = ri, e.id = "R/" + std::string(a.level) + "/" + r.key;
        if (r.side) {
            int sp = -1;
            for (auto &s : r.spawns)
                if (known.count(s.locator)) sp = known[s.locator];
            if (sp < 0) continue;  // (side passages: only through their own arrival points)
            e.spot = sp, e.icon = WI_LADDER, e.name = "Side passage " + std::to_string(++nside), e.sub = "Seen from the side";
            e.desc = L("A ladder passage, seen from the side.");
            a.entries.push_back(e);
            continue;
        }
        if (r.unit != ri) continue;  // (one place per room: its first cell)
        bool instr = false, chest = false, stairs = false, entrance = false, big = false;
        int c0 = r.col, c1 = r.col, r0 = r.row, r1 = r.row, nchest = 0;
        for (const WarpRoom &x : LV.rooms) {
            if (x.side || x.unit != ri) continue;
            big |= &x != &r;
            c0 = std::min(c0, x.col), c1 = std::max(c1, x.col), r0 = std::min(r0, x.row), r1 = std::max(r1, x.row);
            for (auto &f : x.feats) instr |= f.kind == WF_INSTRUMENT, nchest += f.kind == WF_CHEST, stairs |= f.kind == WF_STAIRS;
            for (auto &s : x.spawns) {
                auto k = known.find(s.locator);
                if (k == known.end() || s.locator == "OcarinaWarpPoint") continue;
                bool ent = strstr(kWarpSpots[k->second].label, "Entrance") != NULL;
                entrance |= ent;
                // the room's own arrival point: an entrance first, then stairs, then any
                if (e.spot < 0 || ent || (strstr(kWarpSpots[k->second].label, "stairs") && !strstr(kWarpSpots[e.spot].label, "Entrance")))
                    e.spot = k->second;
            }
        }
        chest = nchest > 0;
        float fy = ((r0 + r1) / 2.0f - LV.r0 + 0.5f) / (LV.r1 - LV.r0 + 1), fx = ((c0 + c1) / 2.0f - LV.c0 + 0.5f) / (LV.c1 - LV.c0 + 1);
        const char *what = instr ? "Instrument room" : entrance ? "Entrance hall" : big ? "Big hall" : chest ? "Chest room" : stairs ? "Stairs room" : "Room";
        e.icon = instr ? WI_NOTE : entrance ? WI_ENTRANCE : stairs ? WI_STAIRS : WI_ROOM;
        e.name = std::string(what) + ", " + compass(fy, fx);
        int k = ++names[e.name];
        if (k > 1) e.name += " " + std::to_string(k);
        e.sub = e.spot >= 0 ? "Arrival point" : "Landing by a doorway";
        // the description: what is in it
        std::string d;
        auto add = [&d](const std::string &s) { d += d.empty() ? s : ", " + s; };
        int nf[WF_N] = {};
        for (const WarpRoom &x : LV.rooms)
            if (!x.side && x.unit == ri)
                for (auto &f : x.feats) nf[f.kind] += !f.mirror;
        char buf[64];
        if (nf[WF_INSTRUMENT]) add(L("an instrument"));
        if (nf[WF_CHEST]) snprintf(buf, sizeof buf, nf[WF_CHEST] > 1 ? L("%d chests") : L("a chest"), nf[WF_CHEST]), add(buf);
        if (nf[WF_STAIRS]) add(L("stairs"));
        if (nf[WF_DOOR_LOCK]) add(L("a key door"));
        if (nf[WF_DOOR_BOSS]) add(L("the boss door"));
        if (nf[WF_LOCKBLOCK]) add(L("a key block"));
        if (nf[WF_SWITCH]) add(L("a switch"));
        if (nf[WF_DOOR_CRACKED]) add(L("a wall to bomb"));
        e.desc = d.empty() ? std::string(L("An empty room.")) : std::string(L("In this room: ")) + d + ".";
        a.entries.push_back(e);
    }
    std::sort(a.entries.begin(), a.entries.end(), [](const Entry &x, const Entry &y) { return x.name < y.name; });
}

static Area *find_area(int sec, const char *name) {
    for (auto &a : g_areas)
        if (a.sec == sec && a.name == name) return &a;
    return nullptr;
}
static void ensure_built(Area &a) {
    if (!a.built && a.sec == SEC_DG) build_dungeon(a);
}
// ---------- warping ----------
static bool entry_blocked(const Entry &e) { return e.spot >= 0 && warp_blocked(kWarpSpots[e.spot].locator); }
static void do_warp(const Entry &e) {
    if (e.spot >= 0) {
        warp_request(kWarpSpots[e.spot].level, kWarpSpots[e.spot].locator);
        LOG("[warp] menu: %s / %s\n", e.level, e.name.c_str());
        return;
    }
    // a room without an arrival point: the nearest one of the level the list has, then Link is moved into the room
    const WarpLevel &LV = warp_level(e.level);
    const WarpRoom &to = LV.rooms[e.room];
    float x, y, z, best = 1e30f;
    const char *loc = nullptr;
    if (!warp_room_landing(LV, e.room, &x, &y, &z)) return;
    for (int i = 0; i < kNumSpots; i++) {
        const WarpSpot &w = kWarpSpots[i];
        if (strcmp(w.level, e.level) || !strcmp(w.locator, "OcarinaWarpPoint") || warp_blocked(w.locator)) continue;
        int ri = LV.find_spawn(w.locator);
        if (ri < 0 || LV.rooms[ri].side) continue;
        float d = (float)((LV.rooms[ri].col - to.col) * (LV.rooms[ri].col - to.col) + (LV.rooms[ri].row - to.row) * (LV.rooms[ri].row - to.row));
        if (d < best) best = d, loc = w.locator;
    }
    if (!loc) return;
    warp_request_place(e.level, loc, x, y, z);
    LOG("[warp] menu: %s / %s (room %s, by %s)\n", e.level, e.name.c_str(), to.key.c_str(), loc);
}

