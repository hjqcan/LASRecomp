static std::string area_key(const Area &a) { return "A" + std::to_string(a.sec) + "|" + a.name; }
static bool area_here(const Area &a, const char *cur) {
    if (!strcmp(cur, "Field") || !*cur) return false;
    if (a.level) return !strcmp(a.level, cur);
    for (int i : a.spots)
        if (!strcmp(kWarpSpots[i].level, cur)) return true;
    return false;
}
static bool matches(const Area &a, const Entry &e, const char *f) {
    std::string fields[] = {e.name, e.sub, a.name, L_line(e.name), L_line(a.name)};
    for (auto &s : fields) {
        std::string x = s, y = f;
        std::transform(x.begin(), x.end(), x.begin(), ::tolower), std::transform(y.begin(), y.end(), y.begin(), ::tolower);
        if (x.find(y) != std::string::npos) return true;
    }
    return false;
}
static bool pressed_right(void) {
    return ImGui::IsKeyPressed(ImGuiKey_GamepadDpadRight) || ImGui::IsKeyPressed(ImGuiKey_GamepadLStickRight) || ImGui::IsKeyPressed(ImGuiKey_RightArrow);
}
static void row_focus(const std::string &key, bool hover_shows, const std::string &show, int area) {
    if (g_focus_req == key) g_focus_req.clear(), opt_focus_item();
    bool foc = opt_item_nav_focused();
    if (foc) g_focus_now = key;
    if (foc || (hover_shows && ImGui::IsItemHovered())) g_show = show, g_show_area = area;
}
// a section / area header row; true when it opened or closed
static bool header(const std::string &key, const char *label, const char *value, bool open, const std::string &show, int area) {
    ImGui::PushID(key.c_str());
    if (open) opt_mark_next();
    opt_shown_next();
    bool hit = opt_link(label, NULL, value);
    ImGui::PopID();
    row_focus(key, true, show, area);
    if (!hit) return false;
    if (open && pressed_right()) return false;  // (Right opens; it never closes)
    if (open) g_open.erase(key);
    else g_open.insert(key);
    g_focus_req = key;
    return true;
}
static std::string entry_desc(const Entry &e) {
    if (!entry_blocked(e)) return e.desc;
    return strncmp(kWarpSpots[e.spot].locator, "Warp_", 5) ? L("You arrive here swimming, so you need the Flippers.")
                                                           : L("This is where Manbo's Mambo drops you. You can't warp here directly.");
}
static bool entry_row(const Area &a, int ai, const Entry &e, const std::string &key, bool with_area, bool enabled) {
    std::string lbl = with_area ? std::string(L_line(a.name)) + "  -  " + L_line(e.name) : std::string(L_line(e.name));
    bool off = !enabled || entry_blocked(e);
    std::string desc = entry_desc(e);
    ImGui::PushID(key.c_str());
    if (off) opt_disable_next();
    opt_shown_next();
    bool go = opt_action(lbl.c_str(), "", desc.c_str(), false);
    ImGui::PopID();
    row_focus(key, true, e.id, ai);
    if (go && !off) { do_warp(e); return true; }
    return false;
}

static void draw_map(void) {
    // what to show: the entry (or area) under the cursor
    Area *a = g_show_area >= 0 && g_show_area < (int)g_areas.size() ? &g_areas[g_show_area] : nullptr;
    const Entry *e = nullptr;
    if (a)
        for (auto &x : a->entries)
            if (x.id == g_show) e = &x;
    float fs = ImGui::GetFontSize();
    ImGui::SetWindowFontScale(1.3f);
    ImGui::TextColored(ImVec4(0.93f, 0.76f, 0.33f, 1), "%s", a ? (e ? L_line(e->name).c_str() : L_line(a->name).c_str()) : L("Warp"));
    ImGui::SetWindowFontScale(1.0f);
    if (a) ImGui::TextDisabled("%s", e ? (std::string(L_line(a->name)) + "  ·  " + L_line(e->sub)).c_str() : L(kSecName[a->sec]));
    ImVec2 avail = ImGui::GetContentRegionAvail();
    float h = std::max(fs * 6, avail.y - fs * 1.3f * 3.5f);
    ImVec2 p0 = ImGui::GetCursorScreenPos(), p1(p0.x + avail.x, p0.y + h);
    ImGui::Dummy(ImVec2(avail.x, h));
    ImDrawList *dl = ImGui::GetWindowDrawList();
    dl->AddRectFilled(p0, p1, IM_COL32(28, 25, 36, 255), 10);
    ImVec2 a0(p0.x + 6, p0.y + 6), a1(p1.x - 6, p1.y - 6);
    if (!a) return;
    {  // under the map: what it shows (the place, or the area's count)
        char buf[64];
        snprintf(buf, sizeof buf, L("%d places"), (int)a->entries.size());
        std::string d = e ? entry_desc(*e) : a->built ? std::string(buf) : std::string();
        ImGui::SetWindowFontScale(1.3f);
        ImGui::PushTextWrapPos(0);
        ImGui::TextUnformatted(d.c_str());
        ImGui::PopTextWrapPos();
        ImGui::SetWindowFontScale(1.0f);
    }
    if (a->sec == SEC_DG && a->level && warp_level(a->level).ok) {
        const WarpLevel &LV = warp_level(a->level);
        std::vector<WarpDot> dots;
        for (auto &x : a->entries) {
            int ri = x.room;
            if (x.spot >= 0) {
                int si = LV.find_spawn(kWarpSpots[x.spot].locator);
                if (si >= 0) {
                    for (auto &s : LV.rooms[si].spawns)
                        if (s.locator == kWarpSpots[x.spot].locator) dots.push_back({si, s.x, s.z, e == &x});
                    continue;
                }
            }
            float lx, ly, lz;
            if (ri >= 0 && warp_room_landing(LV, ri, &lx, &ly, &lz))
                dots.push_back({ri, (lx - LV.rooms[ri].col * 15.0f) / 1.5f, (lz - LV.rooms[ri].row * 12.0f) / 1.5f, e == &x});
        }
        int sel = e ? e->room : -1;
        if (sel >= 0) {
            float mid = a0.y + (a1.y - a0.y) * 0.5f;
            warp_draw_floor(dl, a0, ImVec2(a1.x, mid - 4), LV, sel, dots.data(), (int)dots.size());
            dl->AddLine(ImVec2(a0.x + 8, mid), ImVec2(a1.x - 8, mid), IM_COL32(80, 72, 98, 255), 1);
            warp_draw_room(dl, ImVec2(a0.x, mid + 4), a1, LV, sel, dots.data(), (int)dots.size());
        } else {
            warp_draw_floor(dl, a0, a1, LV, -1, dots.data(), (int)dots.size());
        }
        return;
    }
    // the island
    int cr = e ? e->sq_r : -1, cc = e ? e->sq_c : -1;
    warp_draw_island(dl, a0, a1, g_island, cr, cc, a->sec == SEC_OW && cr < 0 ? a->region : -1);
}

extern "C" bool warp_tab_draw(float scale) {
    if (g_areas.empty()) build_places();
    const char *cur = current_level();
    bool avail = warp_available() != 0;
    int frame = ImGui::GetFrameCount();
    g_back_took = false;
    if (frame - g_last_frame > 1) {  // (the tab just opened) open the area Link is in
        g_focus_prev.clear();
        for (int i = 0; i < (int)g_areas.size(); i++)
            if (area_here(g_areas[i], cur)) {
                g_open.insert("S" + std::to_string(g_areas[i].sec)), g_open.insert(area_key(g_areas[i]));
                ensure_built(g_areas[i]);
                if (g_show.empty() || g_show_area < 0) g_show_area = i, g_show = area_key(g_areas[i]);
            }
        if (g_open.empty()) g_open.insert("S0");
        if (g_show_area < 0) g_show_area = 0, g_show = area_key(g_areas[0]);
    }
    g_last_frame = frame;
    bool started = false;

    // test hooks: LARECOMP_WARP_MENU_PICK=<text> warps to the first place matching <text> through this tab;
    // LARECOMP_WARP_SHOW=<text> opens the list there and shows it on the map
    static int test_state = getenv("LARECOMP_WARP_MENU_PICK") || getenv("LARECOMP_WARP_SHOW") ? 1 : 0;
    if (test_state == 1 && (avail || getenv("LARECOMP_WARP_SHOW"))) {
        const char *want = getenv("LARECOMP_WARP_MENU_PICK") ? getenv("LARECOMP_WARP_MENU_PICK") : getenv("LARECOMP_WARP_SHOW");
        for (int i = 0; i < (int)g_areas.size() && test_state == 1; i++) {
            ensure_built(g_areas[i]);
            for (auto &e : g_areas[i].entries)
                if (matches(g_areas[i], e, want)) {
                    g_open.insert("S" + std::to_string(g_areas[i].sec)), g_open.insert(area_key(g_areas[i]));
                    g_show = e.id, g_show_area = i, g_focus_req = "E" + e.id;
                    if (getenv("LARECOMP_WARP_MENU_PICK")) do_warp(e), started = true, LOG("[warp] menu test pick: %s\n", e.name.c_str());
                    test_state = 2;
                    break;
                }
        }
        test_state = 2;
    }

    // Left: an open area or section closes; on a place, its area closes and takes the cursor
    if (!g_focus_prev.empty() && opt_pressed_left() && !ui_text_busy() && !ImGui::IsPopupOpen("", ImGuiPopupFlags_AnyPopupId)) {
        std::string k = g_focus_prev;
        if (k[0] == 'E') {
            for (auto &a : g_areas)
                for (auto &e : a.entries)
                    if ("E" + e.id == k) { g_open.erase(area_key(a)), g_focus_req = area_key(a); }
        } else if (k[0] == 'A') {
            if (g_open.count(k)) g_open.erase(k);
            else { std::string s = "S" + k.substr(1, 1); g_open.erase(s), g_focus_req = s; }
        } else if (k[0] == 'S' && g_open.count(k)) {
            g_open.erase(k);
        }
    }
    g_focus_now.clear();

    if (!avail) {  // (no header line otherwise: the list starts at the top)
        ImGui::TextDisabled("%s", L("Load a save to warp."));
        ImGui::Spacing();
    }
    opt_begin("##warp", scale, true);
    opt_compact();
    ui_text_inline(true);  // (filters as typed: typed into directly, not through a prompt)
    opt_text("Search", g_filter, sizeof g_filter, "Search places...", NULL);
    ui_text_inline(false);
    bool searching = g_filter[0] != 0;
    for (int s = SEC_OW; s <= SEC_DG; s++) {
        std::string sk = "S" + std::to_string(s);
        std::vector<int> areas;
        for (int i = 0; i < (int)g_areas.size(); i++)
            if (g_areas[i].sec == s) areas.push_back(i);
        if (searching) {  // (only areas with a match; all of them open)
            std::vector<int> hit;
            for (int i : areas) {
                ensure_built(g_areas[i]);
                for (auto &e : g_areas[i].entries)
                    if (matches(g_areas[i], e, g_filter)) { hit.push_back(i); break; }
            }
            areas = hit;
            if (areas.empty()) continue;
        }
        char v[16];
        snprintf(v, sizeof v, "%d", (int)areas.size());
        bool so = searching || g_open.count(sk);
        if (!searching) header(sk, L(kSecName[s]), v, so, g_show, g_show_area);
        else opt_section(kSecName[s]);
        if (!searching && !g_open.count(sk)) continue;
        opt_indent(1);
        for (int ai : areas) {
            Area &a = g_areas[ai];
            std::string ak = area_key(a);
            bool ao = searching || g_open.count(ak);
            if (ao) ensure_built(a);
            char cnt[48];
            if (area_here(a, cur)) snprintf(cnt, sizeof cnt, "%s", L("Link is here"));
            else if (a.built) snprintf(cnt, sizeof cnt, "%d", (int)a.entries.size());
            else cnt[0] = 0;
            if (!searching) {
                if (header(ak, L_line(a.name).c_str(), cnt, ao, ak, ai) && g_open.count(ak)) ensure_built(a);
                if (!g_open.count(ak)) continue;
            } else {
                opt_section(L_line(a.name).c_str());
            }
            opt_indent(1);
            for (auto &e : a.entries) {
                if (searching && !matches(a, e, g_filter)) continue;
                started |= entry_row(a, ai, e, "E" + e.id, false, avail);
            }
            opt_indent(-1);
        }
        opt_indent(-1);
    }
    opt_split();
    draw_map();
    opt_split_end();
    g_focus_prev = g_focus_now;
    return started;
}
